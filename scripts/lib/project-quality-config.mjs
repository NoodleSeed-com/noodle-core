import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

function matches(pattern, files) {
  const expression = pattern
    .split('**')
    .map((part) =>
      part
        .split('*')
        .map((literal) => literal.replace(/[|\\{}()[\]^$+?.]/g, '\\$&'))
        .join('[^/]*'),
    )
    .join('.*');
  const regex = new RegExp(`^${expression}$`);
  return files.some((file) => regex.test(file));
}

/** Derive public policy from the actual projection, never a second package inventory. */
export function projectQualityConfig(config, destinations) {
  const roots = new Set(
    destinations
      .filter((file) => /^(packages|apps)\/[^/]+\/package\.json$/.test(file))
      .map((file) => file.slice(0, -'/package.json'.length)),
  );
  const scopes = config.packageScopes;
  const boundaries = config.packageBoundaries ?? {};
  return {
    _generated: 'scripts/gen-quality-gates.mjs from quality-gates.config.json; do not edit',
    escapeHatches: config.escapeHatches,
    packageScopes: {
      defaultMaxSourceLines: scopes.defaultMaxSourceLines,
      warningRatio: scopes.warningRatio,
      envelopes: scopes.envelopes
        .filter((entry) => roots.has(entry.path))
        .map((entry) => ({
          ...entry,
          ...(entry.modules
            ? {
                modules: entry.modules.filter((module) =>
                  destinations.some((file) => file.startsWith(`${entry.path}/${module.path}/`)),
                ),
              }
            : {}),
        })),
      commercialVendorDependencies: scopes.commercialVendorDependencies,
    },
    packageBoundaries: {
      allowServiceDevDependencies: (boundaries.allowServiceDevDependencies ?? []).filter((entry) =>
        roots.has(entry.path),
      ),
      allowCrossPackageSourceImports: (boundaries.allowCrossPackageSourceImports ?? []).filter(
        (entry) => matches(entry.from, destinations) && matches(entry.to, destinations),
      ),
      ...(boundaries.allowUndeclaredExternalImports
        ? {
            allowUndeclaredExternalImports: boundaries.allowUndeclaredExternalImports.filter(
              (entry) => matches(entry.file, destinations),
            ),
          }
        : {}),
    },
    // Zero-edge restrictions must survive even when the forbidden cluster is currently absent.
    carveOutSeams: (config.carveOutSeams ?? []).filter((entry) => roots.has(entry.package)),
  };
}

export async function projectedQualityConfig(root) {
  const manifestFile = path.join(root, 'opensource-projection.json');
  if (!existsSync(manifestFile)) return undefined; // Already-projected Core has no private projector.
  const { buildProjectionPlan, loadProjectionManifest } = await import('./oss-projection.mjs');
  const manifest = loadProjectionManifest(manifestFile);
  const plan = buildProjectionPlan({ root, manifest });
  const config = JSON.parse(readFileSync(path.join(root, 'quality-gates.config.json'), 'utf8'));
  const generated = {
    file: path.join(root, manifest.overlayDirectory, 'quality-gates.config.json'),
    text: `${JSON.stringify(
      projectQualityConfig(
        config,
        plan.files.map((entry) => entry.destination),
      ),
      null,
      2,
    )}\n`,
  };
  // The generated bytes must already satisfy the same formatter as dev:ready --fix and CI.
  generated.text = execFileSync(
    process.execPath,
    [
      path.join(root, 'node_modules/@biomejs/biome/bin/biome'),
      'format',
      '--stdin-file-path',
      'quality-gates.config.json',
    ],
    { cwd: root, input: generated.text, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] },
  );
  return generated;
}

export async function checkProjectedQualityConfig(root) {
  const projected = await projectedQualityConfig(root);
  if (!projected) return [];
  return existsSync(projected.file) && readFileSync(projected.file, 'utf8') === projected.text
    ? []
    : [
        'public quality config is stale; run node scripts/gen-quality-gates.mjs (edit only the root policy)',
      ];
}
